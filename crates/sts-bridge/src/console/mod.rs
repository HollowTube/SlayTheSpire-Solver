//! Dev console commands as typed values, sent and verified.
//!
//! The game's console reports success for commands that did nothing, and the
//! bridge drops its result altogether, so [`Session::console`] never trusts
//! the reply: it sends the command once the game is settled and returns only
//! when the state afterwards shows the effect (see [`check`]).
//!
//! The command list is generated from the game files
//! (`scripts/console_catalog.py extract`), compiled into [`catalog`], and every
//! constructor names its catalog entry and pins its usage string, so a game
//! patch that renames or reshapes a command fails the build.

pub(crate) mod check;
mod ids;

use std::fmt;
use std::time::Duration;

