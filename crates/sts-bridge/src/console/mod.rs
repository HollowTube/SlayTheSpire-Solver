use crate::state::{CardId, GameState, Screen};

pub use ids::{slugify, Encounter, PowerName, Relic, UnknownId, NIBBITS_WEAK};

/// The command list of one game version, generated by `build.rs` from
/// `catalog/<version>/console_commands.json`.
pub mod catalog {
    /// One console command, as the game declares it.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub struct CommandSpec {
        pub name: &'static str,
        /// The usage string, e.g. `<card-id:string> [pileName:string]`.
        pub args: &'static str,
        pub description: &'static str,
        pub networked: bool,
        pub debug_only: bool,
        /// Whether it moves the run to another room or act. Sending one while
        /// a run loads crashes the game.
        pub enters_room: bool,
    }

    include!(concat!(env!("OUT_DIR"), "/console_catalog.rs"));

    /// The command named `name`, if the game has it.
    pub fn find(name: &str) -> Option<&'static CommandSpec> {
        ALL.iter().find(|c| c.name == name)
    }
}

/// Fails the build when a command's usage string differs from what the
/// constructor was written for.
macro_rules! pin_args {
    ($($spec:ident => $args:literal),* $(,)?) => {
        $(
            const _: () = assert!(
                ids::str_eq(catalog::$spec.args, $args),
                concat!("the catalog usage of `", stringify!($spec), "` changed: review its constructor")
            );
        )*
    };
}

pin_args! {
    FIGHT => "<id:string>",
    DAMAGE => "<amount:int> <target-index:int>",
    HEAL => "<amount:int> [index:int]",
    BLOCK => "<int:amount> <target-index:int>",
    ENERGY => "<amount:int>",
    POWER => "<id:string> <amount:int> <target-index:int>",
    CARD => "<card-id:string> [pileName:string]",
    REMOVE_CARD => "<id:string> [pileName:string]",
    RELIC => "[add|remove] <relic-id:string>",
    DRAW => "<count:int>",
    UPGRADE => "<hand-index:int>",
    WIN => "",
    INSTANT => "",
}

/// Who a command acts on. The console indexes creatures as the player first,
/// then the enemies.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Target {
    Player,
    /// The enemy at this index of `CombatView::enemies`.
    Enemy(usize),
}

impl Target {
    fn creature_index(self) -> usize {
        match self {
            Target::Player => 0,
            Target::Enemy(i) => 1 + i,
        }
    }
}

/// A pile a card can be added to in combat.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CombatPile {
    Hand,
    Draw,
    Discard,
    Exhaust,
}

impl CombatPile {
    pub fn as_str(&self) -> &'static str {
        match self {
            CombatPile::Hand => "hand",
            CombatPile::Draw => "draw",
            CombatPile::Discard => "discard",
            CombatPile::Exhaust => "exhaust",
        }
    }
}

/// A console command a fixture needs, typed.
#[derive(Debug, Clone, PartialEq)]
#[non_exhaustive]
pub enum ConsoleCommand {
    /// Jumps to an encounter (a room change).
    Fight(Encounter),
    Damage {
        target: Target,
        amount: u32,
    },
    DamageAllEnemies {
        amount: u32,
    },
    /// Heals the player; no console command heals an enemy.
    HealPlayer {
        amount: u32,
    },
    Block {
        target: Target,
        amount: u32,
    },
    Energy {
        amount: u32,
    },
    /// Adds `amount` of a power. The game takes positive amounts only.
    Power {
        power: PowerName,
        amount: u32,
        target: Target,
    },
    AddCard {
        card: CardId,
        pile: CombatPile,
    },
    /// Removes the first copy of the card from the hand.
    RemoveCardFromHand {
        card: CardId,
    },
    /// Removes the first copy of the card from the master deck, in or out of
    /// combat; a combat in progress keeps its own copies.
    RemoveCardFromDeck {
        card: CardId,
    },
    RelicAdd(Relic),
    RelicRemove(Relic),
    Draw {
        count: u32,
    },
    Upgrade {
        hand_index: usize,
    },
    /// Wins the combat.
    Win,
    /// The console's instant-mode switch, which only flips it. Use
    /// [`Session::set_instant`]; [`Session::console`] refuses this.
    ToggleInstant,
    /// A raw console line, for checking that a command the game rejects or
    /// ignores is reported as having no effect. Only its first word is
    /// checked, against the catalog; the postcondition is that the state
    /// changed.
    Probe(String),
}

impl ConsoleCommand {
    /// The catalog entry of the command this sends; `None` for a [`Probe`]
    /// of a command the game does not have.
    ///
    /// [`Probe`]: ConsoleCommand::Probe
    pub fn spec(&self) -> Option<&'static catalog::CommandSpec> {
        use ConsoleCommand as C;
        Some(match self {
            C::Fight(_) => &catalog::FIGHT,
            C::Damage { .. } | C::DamageAllEnemies { .. } => &catalog::DAMAGE,
            C::HealPlayer { .. } => &catalog::HEAL,
            C::Block { .. } => &catalog::BLOCK,
            C::Energy { .. } => &catalog::ENERGY,
            C::Power { .. } => &catalog::POWER,
            C::AddCard { .. } => &catalog::CARD,
            C::RemoveCardFromHand { .. } | C::RemoveCardFromDeck { .. } => &catalog::REMOVE_CARD,
            C::RelicAdd(_) | C::RelicRemove(_) => &catalog::RELIC,
            C::Draw { .. } => &catalog::DRAW,
            C::Upgrade { .. } => &catalog::UPGRADE,
            C::Win => &catalog::WIN,
            C::ToggleInstant => &catalog::INSTANT,
            C::Probe(line) => return catalog::find(line.split_whitespace().next()?),
        })
    }

    /// Whether the command moves the run to another room or act, from the
    /// catalog. Such a command is sent only once the run has finished loading.
    pub fn enters_room(&self) -> bool {
        self.spec().is_some_and(|s| s.enters_room)
    }

    /// The exact console line.
    pub fn line(&self) -> String {
        use ConsoleCommand as C;
        let name = |spec: &catalog::CommandSpec| spec.name;
        match self {
            C::Fight(e) => format!("{} {e}", name(&catalog::FIGHT)),
            C::Damage { target, amount } => {
                format!(
                    "{} {amount} {}",
                    name(&catalog::DAMAGE),
                    target.creature_index()
                )
            }
            C::DamageAllEnemies { amount } => format!("{} {amount}", name(&catalog::DAMAGE)),
            C::HealPlayer { amount } => format!("{} {amount}", name(&catalog::HEAL)),
            C::Block { target, amount } => {
                format!(
                    "{} {amount} {}",
                    name(&catalog::BLOCK),
                    target.creature_index()
                )
            }
            C::Energy { amount } => format!("{} {amount}", name(&catalog::ENERGY)),
            C::Power {
                power,
                amount,
                target,
            } => format!(
                "{} {power} {amount} {}",
                name(&catalog::POWER),
                target.creature_index()
            ),
            C::AddCard { card, pile } => {
                format!(
                    "{} {} {}",
                    name(&catalog::CARD),
                    card.sts2_id(),
                    pile.as_str()
                )
            }
            C::RemoveCardFromHand { card } => {
                format!("{} {} hand", name(&catalog::REMOVE_CARD), card.sts2_id())
            }
            C::RemoveCardFromDeck { card } => {
                format!("{} {} deck", name(&catalog::REMOVE_CARD), card.sts2_id())
            }
            C::RelicAdd(r) => format!("{} add {r}", name(&catalog::RELIC)),
            C::RelicRemove(r) => format!("{} remove {r}", name(&catalog::RELIC)),
            C::Draw { count } => format!("{} {count}", name(&catalog::DRAW)),
            C::Upgrade { hand_index } => format!("{} {hand_index}", name(&catalog::UPGRADE)),
            C::Win => name(&catalog::WIN).to_string(),
            C::ToggleInstant => name(&catalog::INSTANT).to_string(),
            C::Probe(line) => line.clone(),
        }
    }
}

impl fmt::Display for ConsoleCommand {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.line())
    }
}

/// The longest one console command may take to settle: the bridge answers in
/// 0.7 to 1 s per call while the game is unfocused, and a read is five calls.
pub const CONSOLE_TIMEOUT: Duration = Duration::from_secs(45);

/// How long [`Session::console_with`] waits, for one call.
#[derive(Debug, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub struct ConsoleWait {
    /// For the settle waits before and after the command.
    pub settle: SettlePolicy,
    /// For the wait for a stable in-run screen before a room-changing command;
    /// its probe policy is the dwell, and `run_load` bounds the wait.
    pub room_ready: Timeouts,
}

impl ConsoleWait {
    /// The session's policy with its timeout raised to [`CONSOLE_TIMEOUT`].
    pub fn for_session(policy: &SettlePolicy) -> Self {
        let timeout = policy.timeout.max(CONSOLE_TIMEOUT);
        Self {
            settle: policy.clone().with_timeout(timeout),
            room_ready: Timeouts::default().with_run_load(timeout),
        }
    }

    pub fn with_settle(mut self, settle: SettlePolicy) -> Self {
        self.settle = settle;
        self
    }

    pub fn with_room_ready(mut self, room_ready: Timeouts) -> Self {
        self.room_ready = room_ready;
        self
    }
}

/// The game's `msg` from a console reply that succeeded, when it has one.
pub fn reply_message(ack: &Ack) -> Option<String> {
    ack.reply.get("msg")?.as_str().map(str::to_string)
}

/// The instant-mode flag, polled for stability on its own: a `Health` also
/// carries a latency that changes on every read.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct FastMode(Option<bool>);

impl Observation for FastMode {
    fn screen(&self) -> Option<&Screen> {
        None
    }
}

impl<B: Backend> Session<B> {
    /// Runs a console command and returns the settled state in which its
    /// effect is visible.
    ///
    /// This is [`Session::act`] for the console, under [`ConsoleWait`]'s longer
    /// timeout: nothing is sent mid-transition or while a run loads, a command
    /// the game would reject is [`BridgeError::ActionRefused`] and never
    /// sent, and the state afterwards must show the command's effect. The
    /// game's own success flag is not trusted: a command that reports success
    /// and does nothing is [`BridgeError::PostconditionFailed`] naming the
    /// field that did not change.
    ///
    /// A room-changing command (see [`ConsoleCommand::enters_room`]) also
    /// waits for the run to hold a stable in-run screen first.
    ///
    /// [`Session::act`]: crate::Session::act
    pub fn console(&mut self, command: &ConsoleCommand) -> Result<GameState, BridgeError> {
        let wait = ConsoleWait::for_session(self.policy());
        self.console_with(command, &wait)
    }

    /// [`Session::console`] under `wait`. The session's own policy is
    /// restored on every path.
    pub fn console_with(
        &mut self,
        command: &ConsoleCommand,
        wait: &ConsoleWait,
    ) -> Result<GameState, BridgeError> {
        let saved = self.policy().clone();
        self.set_policy(wait.settle.clone());
        let result = self.send_console(command, wait);
        self.set_policy(saved);
        result
    }

    fn send_console(
        &mut self,
        command: &ConsoleCommand,
        wait: &ConsoleWait,
    ) -> Result<GameState, BridgeError> {
        let command = Command::Console(command.clone());
        if matches!(&command, Command::Console(c) if c.enters_room()) {
            refuse_while_loading(self.backend_mut(), &command)?;
            // Without a run the wait below would never end; refuse at once.
            let no_run = match self.backend_mut().probe() {
                Err(BridgeError::ExplorerUnavailable { .. }) => true,
                Ok(probe) => probe.run_in_progress != Some(true),
                Err(e) => return Err(e),
            };
            if no_run {
                return Err(BridgeError::ActionRefused {
                    action: command.to_string(),
                    reason: "no run in progress".to_string(),
                });
            }
            wait_run_ready(self.backend_mut(), &wait.room_ready)?;
        }
        self.act(&command)
    }

    /// Sets instant mode on or off and returns the mode now in force.
    ///
    /// The console only toggles it, so this reads the current mode first and
    /// sends nothing when it already matches; otherwise it sends one toggle
    /// and waits for the mode to read back as asked. It never toggles blind
    /// and never sends a second toggle. A bridge that does not report the mode
    /// is [`BridgeError::ActionRefused`]; a toggle that settles without the
    /// mode changing is [`BridgeError::PostconditionFailed`].
    pub fn set_instant(&mut self, on: bool) -> Result<bool, BridgeError> {
        let wait = ConsoleWait::for_session(self.policy());
        self.set_instant_with(on, &wait)
    }

    /// [`Session::set_instant`] waiting as `wait.settle` says.
    pub fn set_instant_with(&mut self, on: bool, wait: &ConsoleWait) -> Result<bool, BridgeError> {
        let toggle = Command::Console(ConsoleCommand::ToggleInstant);
        refuse_while_loading(self.backend_mut(), &toggle)?;
        let Some(current) = self.backend_mut().health()?.fast_mode else {
            return Err(BridgeError::ActionRefused {
                action: "instant".to_string(),
                reason: "the bridge does not report fast_mode".to_string(),
            });
        };
        if current == on {
            return Ok(on);
        }
        let ack = self.backend_mut().send(&toggle)?;
        let backend = self.backend_mut();
        let outcome = poll(
            &wait.settle,
            || backend.health().map(|h| FastMode(h.fast_mode)),
            |m| m.0 == Some(on),
        )?;
        match outcome {
            Ok(_) => Ok(on),
            Err(Expired { last, stable, .. }) if stable && last.0.is_some() => {
                let mode = |m: bool| if m { "on" } else { "off" };
                let note = reply_message(&ack).map_or(String::new(), |m| format!(" (game: {m})"));
                Err(BridgeError::PostconditionFailed {
                    action: toggle.to_string(),
                    expected: format!("instant mode {}", mode(on)),
                    observed: format!("instant mode {}{note}", mode(!on)),
                })
            }
            Err(Expired { waited, .. }) => Err(BridgeError::NotSettled {
                waited,
                screen: None,
                unmet: format!("instant mode {}", if on { "on" } else { "off" }),
            }),
        }
    }
}
