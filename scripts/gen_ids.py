#!/usr/bin/env python3
"""Write python/sts_sim/sim/_registry.pyi from the live registry rows.

The rows come from the built `_sts_sim` extension (`crates/sts-ids`), so build
it first (`uv pip install -e ".[dev]"`).

Usage:
    python scripts/gen_ids.py          # regenerate in place
    python scripts/gen_ids.py --check  # fail if the committed stub is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).parent.parent
STUB = REPO_ROOT / "python" / "sts_sim" / "sim" / "_registry.pyi"

sys.path.insert(0, str(REPO_ROOT / "python"))

_HEADER = '''\
# Generated by scripts/gen_ids.py from crates/sts-ids/src/registry.rs. Do not edit.
from enum import Enum
from typing import TypedDict

class CardRow(TypedDict):
    variant: str
    display: str
    sts2_id: str
    bridge_names: list[str]
    in_card_pool: bool

class MonsterRow(TypedDict):
    variant: str
    display: str
    sts2_id: str
    bridge_names: list[str]
    hp: int | None
    encounter: str | None

class StatusRow(TypedDict):
    variant: str
    display: str
    bridge_names: list[str]

CARD_ROWS: tuple[CardRow, ...]
MONSTER_ROWS: tuple[MonsterRow, ...]
STATUS_ROWS: tuple[StatusRow, ...]
MULTI_MONSTER_ENCOUNTERS: tuple[str, ...]

def display_to_member(display: str) -> str: ...
def encounter_member(key: str) -> str: ...
'''


def _enum(name: str, members: list[tuple[str, str]], extra: str = "") -> str:
    body = "".join(f'    {m} = "{v}"\n' for m, v in members)
    return f"\nclass {name}(str, Enum):\n{extra}{body}"


def render() -> str:
    try:
        from sts_sim.sim import _registry as r
    except ImportError as e:
        sys.exit(
            f"ERROR: cannot import the registry ({e}).\n"
            'Build the extension first: uv pip install -e ".[dev]"'
        )

    return (
        _HEADER
        + _enum("CardName", [(m.name, m.value) for m in r.CardName])
        + _enum("MonsterName", [(m.name, m.value) for m in r.MonsterName])
        + _enum(
            "StatusName",
            [(m.name, m.value) for m in r.StatusName],
            extra="    bridge_classes: tuple[str, ...]\n",
        )
        + _enum("Encounter", [(m.name, m.value) for m in r.Encounter])
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if the committed stub differs (for CI)",
    )
    parser.add_argument("--stub", type=Path, default=STUB, help=argparse.SUPPRESS)
    args = parser.parse_args()

    stub: Path = args.stub
    generated = render()
    current = stub.read_text() if stub.exists() else ""
    rel = stub.relative_to(REPO_ROOT) if stub.is_relative_to(REPO_ROOT) else stub
    if args.check:
        if current != generated:
            print(f"STALE: {rel}", file=sys.stderr)
            print("\nRun `python scripts/gen_ids.py` to regenerate.", file=sys.stderr)
            sys.exit(1)
        print(f"OK: {rel} is up to date.")
        return
    if current == generated:
        print(f"Nothing to do — {rel} is already up to date.")
        return
    stub.write_text(generated)
    print(f"Updated {rel}")


if __name__ == "__main__":
    main()
